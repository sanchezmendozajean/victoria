// Builds src/renderer/icons/catalog.generated.ts from the approved mockup catalog (design/icons.js).
// Usage: pnpm icons:gen
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(path.join(root, 'design', 'icons.js'), 'utf8');

const sandbox = {
  window: {},
  customElements: { get: () => true, define: () => undefined },
  HTMLElement: class {},
};
vm.runInNewContext(source, sandbox);
const { cats, map } = sandbox.window.VICONS;

const lines = [
  '// Generated by scripts/gen-icons.mjs from design/icons.js. Do not edit by hand.',
  '// 24-px grid, stroke and fill resolved by <Icon> (currentColor).',
  '',
  'export const ICONS = {',
];
for (const cat of cats) {
  lines.push(`  // ${cat.name}`);
  for (const { id } of cat.icons) lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(map[id].m)},`);
}
lines.push('} as const;', '', 'export type IconId = keyof typeof ICONS;', '');
writeFileSync(path.join(root, 'src', 'renderer', 'icons', 'catalog.generated.ts'), lines.join('\n'));
console.log(`Wrote ${Object.keys(map).length} icons.`);
