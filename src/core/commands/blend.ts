// Mezcla (specs/03 · Mezcla): objects blended into a group made of the key objects and the generated steps
// between each consecutive pair. The group remembers its keys (`GroupNode.blend`), so the step count can change
// later; Expandir forgets that, Liberar gives the key objects back. The steps are regenerated by the session
// (`blend/live.ts`) whenever a key object changes.

const mapAnchor = (m: Matrix, a: Anchor): Anchor => ({ ...a, p: applyToPoint(m, a.p), in: a.in && applyToPoint(m, a.in), out: a.out && applyToPoint(m, a.out) });

/** True when `node` is a group created by Mezcla that is still live. */
export const isBlendGroup = (node: Node | null | undefined): node is GroupNode => !!node && node.type === 'group' && !!node.blend;

/** Paint order (bottom to top) of every object of the Space. */
function paintOrder(space: Space): Map<string, number> {
  const order = new Map<string, number>();
  const walk = (children: readonly LayerChild[]) => {
    for (const child of children) {
      if (isLayer(child)) {
        walk(child.children);
        continue;
      }
      order.set(child.id, order.size);
      if (child.type === 'group' || child.type === 'clipGroup') walk(child.children);
    }
  };
  for (const layer of space.layers) walk(layer.children);
  return order;
}

/** Objects that blend with `ids`, bottom to top: paths and live shapes with a single contour. */
function blendable(space: Space, ids: readonly string[]): Node[] {
  const order = paintOrder(space);
  return ids
    .map((id) => frameOf(space, id)?.node)
    .filter((n): n is Node => !!n && n.visible && contourOf(n) !== null)
    .sort((a, b) => (order.get(a.id) ?? 0) - (order.get(b.id) ?? 0));
}

/** How many of the objects can take part in a blend (it needs at least two). */
export const blendableCount = (space: Space, ids: readonly string[]): number => blendable(space, ids).length;

/**
 * Objeto › Mezcla › Crear (Alt+Ctrl+B): the selected objects (at least two paths or shapes, taken bottom to top)
 * become one group that blends them in `steps` intermediate objects per pair. It sits where the topmost was.
 */
export function makeBlend(space: Space, ids: readonly string[], steps: number, newIds: IdGenerator, equidistant = false): PathfinderResult | null {
  const nodes = blendable(space, ids);
  if (nodes.length < 2) return null;
  const count = clampBlendSteps(steps);
  const top = nodes[nodes.length - 1] as Node;
  const toLocal = containerInverse(space, top.id);
  const keys = nodes.map((node) => {
    const world = (frameOf(space, node.id) as NonNullable<ReturnType<typeof frameOf>>).world;
    const m = multiply(toLocal, world);
    const contour = contourOf(node) as SubPath;
    const key = createPath(newIds, contour.anchors.map((a) => mapAnchor(m, a)), contour.closed);
    key.appearance = deepClone(node.appearance);
    key.opacity = node.opacity;
    key.blendMode = node.blendMode;
    return key;
  });
  const group = createGroup(newIds, assembleBlend(keys, count, newIds, equidistant));
  group.blend = makeBlendInfo(count, keys, equidistant);
  const others = nodes.filter((n) => n !== top).map((n) => n.id);
  const commands: Command[] = [replaceNode(space.id, top.id, [group])];
  if (others.length > 0) commands.push(removeNodes(space.id, others));
  return { command: combineCommands('blend.make', commands), resultIds: [group.id] };
}

/** The live blends among `ids`. */
export const blendGroups = (space: Space, ids: readonly string[]): GroupNode[] => ids.map((id) => frameOf(space, id)?.node).filter(isBlendGroup);

export interface BlendOptions {
  steps: number;
  equidistant: boolean;
}

/** Objeto › Mezcla › Opciones: changes the steps and/or the spacing of the blends in `ids`. Null when none is a live blend. */
export function setBlendOptions(space: Space, ids: readonly string[], patch: Partial<BlendOptions>, newIds: IdGenerator): Command | null {
  const replacements: Array<{ id: string; nodes: Node[] }> = [];
  for (const group of blendGroups(space, ids)) {
    const info = group.blend as NonNullable<GroupNode['blend']>;
    const steps = clampBlendSteps(patch.steps ?? info.steps);
    const equidistant = patch.equidistant ?? info.equidistant === true;
    const base = { ...info };
    delete base.equidistant;
    const next = refreshOf({ ...group, blend: { ...base, steps, ...(equidistant ? { equidistant } : {}) } }, newIds);
    if (next.blend) replacements.push({ id: group.id, nodes: [{ ...group, blend: next.blend, children: next.children } as GroupNode] });
  }
  return replacements.length > 0 ? replaceNodes(space.id, replacements, 'blend.options', 'options') : null;
}

/** Objeto › Mezcla › Opciones: only the number of steps. */
export const setBlendSteps = (space: Space, ids: readonly string[], steps: number, newIds: IdGenerator): Command | null => setBlendOptions(space, ids, { steps }, newIds);

/** Objeto › Mezcla › Expandir: the blend stops being live; the group and every object in it stay. */
export function expandBlends(space: Space, ids: readonly string[]): PathfinderResult | null {
  const groups = blendGroups(space, ids);
  if (groups.length === 0) return null;
  const replacements = groups.map((group) => {
    const rest = deepClone(group) as GroupNode;
    delete rest.blend;
    return { id: group.id, nodes: [rest] };
  });
  return { command: replaceNodes(space.id, replacements, 'blend.expand'), resultIds: groups.map((g) => g.id) };
}

/** Objeto › Mezcla › Liberar: the generated steps go away and the key objects come back as separate paths. */
export function releaseBlends(space: Space, ids: readonly string[]): PathfinderResult | null {
  const replacements: Array<{ id: string; nodes: Node[] }> = [];
  const resultIds: string[] = [];
  for (const group of blendGroups(space, ids)) {
    const nodes = blendKeys(group).map((key) => ({ ...deepClone(key), transform: multiply(group.transform, key.transform) }) as PathNode);
    if (nodes.length === 0) continue;
    for (const node of nodes) resultIds.push(node.id);
    replacements.push({ id: group.id, nodes });
  }
  if (replacements.length === 0) return null;
  return { command: replaceNodes(space.id, replacements, 'blend.release'), resultIds };
}
